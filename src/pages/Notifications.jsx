import { useEffect, useState } from 'react';
import { motion } from 'framer-motion';
import { BellRing, CheckCheck } from 'lucide-react';
import { Page3D, TiltCard } from '../components/fx.jsx';
import api from '../services/api.js';

export default function Notifications() {
  const [notifs, setNotifs] = useState([]);
  const [error, setError] = useState('');

  const load = () => api.get('/notifications').then(({ data }) => setNotifs(data))
    .catch(() => setError('Notification center needs the backend. Reminders are generated by a daily server job (08:00) while it runs.'));

  useEffect(() => { load(); }, []);

  const mark = async (id) => {
    try { await api.patch(`/notifications/${id}/read`); } catch { /* offline */ }
    setNotifs((p) => p.map((n) => (n.id === id ? { ...n, read: true } : n)));
  };

  const markAll = async () => {
    await Promise.all(notifs.filter((n) => !n.read).map((n) => api.patch(`/notifications/${n.id}/read`).catch(() => {})));
    setNotifs((p) => p.map((n) => ({ ...n, read: true })));
  };

  return (
    <Page3D>
      <div className="container" style={{ maxWidth: 760 }}>
        <div className="hero">
          <div><h1>Notifications 🔔</h1><p className="muted">{notifs.filter((n) => !n.read).length} unread • deadline reminders, overdue alerts, completions.</p></div>
          <button className="btn ghost" onClick={markAll}><CheckCheck size={15} /> Mark all read</button>
        </div>
        {error && <div className="alert warn">{error}</div>}
        {notifs.map((n, i) => (
          <motion.div key={n.id} initial={{ opacity: 0, x: -14 }} animate={{ opacity: 1, x: 0 }} transition={{ delay: Math.min(i * 0.04, 0.4) }}>
            <TiltCard className="panel" glow={n.read ? '#64748b' : '#38bdf8'}>
              <div className="row" style={{ marginTop: 0, alignItems: 'center' }}>
                <BellRing size={18} color={n.read ? '#64748b' : '#38bdf8'} />
                <div style={{ flex: 1 }}>
                  <b>{n.title}</b> <span className="chip">{n.kind}</span>
                  <div className="muted">{n.message}</div>
                </div>
                {!n.read && <button className="btn small" onClick={() => mark(n.id)}>Mark read</button>}
              </div>
            </TiltCard>
          </motion.div>
        ))}
        {notifs.length === 0 && !error && <p className="muted">All quiet ✨ Complete a task or wait for the 08:00 reminder job.</p>}
      </div>
    </Page3D>
  );
}
